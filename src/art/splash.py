WHITE=(215,242,247); DIM=(90,110,120)
def width(s,f,p): return (sum(len(f[c][0])+1 for c in s)-1)*p
def text(d,s,f,x,y,p,ds,colfn):
    for c in s:
        g=f[c]
        for r,row in enumerate(g):
            for k,ch in enumerate(row):
                if ch=='1': d.rectangle([x+k*p,y+r*p,x+k*p+ds-1,y+r*p+ds-1],fill=colfn(c))
        x+=(len(g[0])+1)*p
def splash(W,H,acc,brand=None,brandcol=None):
    """brand: list of (text, colour) per word; None = public subtitle"""
    im=Image.new("RGB",(W,H),(0,0,0)); d=ImageDraw.Draw(im)
    p=10 if W>=800 else (6 if W>=480 else 4); ds=max(1,int(p*0.78))
    gp=p*2
    for y in range(gp//2,H,gp):
        for x in range(gp//2,W,gp): d.rectangle([x,y,x+max(1,p//4),y+max(1,p//4)],fill=(22,28,31))
    s="TR4CEPIL0T"; tw=width(s,BIG,p); th=7*p; trail=10
    if brand:
        bp=6 if W>=800 else (4 if W>=480 else 3); bs=" ".join(w for w,_ in brand); bw=width(bs,F8,bp); bh=8*bp; gap=4*p
    else:
        bp=max(1,p//2); bw=width("EDGETX FPV COPILOT",SM,bp); bh=5*bp; gap=3*p
    x0=(W-tw)//2   # centre on the word only; the trail sits to its left
    y0=(H-(th+gap+bh))//2
    for i in range(trail):
        k=((i+1)/trail)**2; c=tuple(int(18+(acc[j]-18)*k) for j in range(3)); sz=max(1,int(ds*(0.45+0.55*k)))
        cx=x0-(trail-i+1)*p; cy=y0+3*p+(ds-sz)//2
        d.rectangle([cx+(ds-sz)//2,cy,cx+(ds-sz)//2+sz-1,cy+sz-1],fill=c)
    text(d,s,BIG,x0,y0,p,ds,lambda c: acc if c in "40" else WHITE)
    yb=y0+th+gap
    if brand:
        x=(W-bw)//2
        for w,col in brand:
            text(d,w,F8,x,yb,bp,max(1,int(bp*0.8)),lambda c,col=col: (acc if c=='&' else col))
            x+=width(w+" ",F8,bp)+bp
    else:
        text(d,"EDGETX FPV COPILOT",SM,x0+(tw-bw)//2,yb,bp,max(1,int(bp*0.8)),lambda c: DIM)
    return im
